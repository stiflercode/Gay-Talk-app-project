    }

    packaging {
        jniLibs {
            useLegacyPackaging = true
            pickFirsts += setOf("lib/arm64-v8a/libaosl.so", "lib/armeabi-v7a/libaosl.so", "lib/x86/libaosl.so", "lib/x86_64/libaosl.so")
        }
    }
}

